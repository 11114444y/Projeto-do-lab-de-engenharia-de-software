-- Schema inicial do projeto de testes. O acesso ao banco é feito pela Edge Function.
-- As tabelas ficam com RLS ativo e sem políticas públicas; a service role da função
-- contorna RLS, após a função validar a sessão e as permissões do usuário.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text not null unique,
  role text not null check (role in ('worker', 'employer')),
  company text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.jobs (
  id bigint generated by default as identity (start with 1000) primary key,
  employer_id uuid not null references public.profiles(id) on delete cascade,
  data jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists jobs_employer_id_idx on public.jobs(employer_id);

create table if not exists public.applications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  job_id bigint not null,
  job_title text not null,
  company text not null,
  status text not null default 'Em análise'
    check (status in ('Em análise', 'Entrevista', 'Reprovado', 'Aprovado')),
  created_at timestamptz not null default now(),
  unique(user_id, job_id)
);

create index if not exists applications_user_id_idx on public.applications(user_id);

create table if not exists public.simulations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  data jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists simulations_user_id_created_at_idx
  on public.simulations(user_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.jobs enable row level security;
alter table public.applications enable row level security;
alter table public.simulations enable row level security;
